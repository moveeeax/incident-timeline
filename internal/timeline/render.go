package timeline

import (
	"strings"
	"time"
)

const tsLayout = "2006-01-02 15:04:05"

// Markdown renders the timeline as a postmortem-ready Markdown document: a
// summary block with the lifecycle metrics followed by a chronological table.
// All times are shown in the timeline's display timezone.
func (t *Timeline) Markdown() string {
	var b strings.Builder
	tz := t.Loc.String()

	b.WriteString("# " + t.Title + "\n\n")
	b.WriteString("_Times in " + tz + ". Generated by [incident-timeline](https://github.com/moveeeax/incident-timeline)._\n\n")

	b.WriteString("## Summary\n\n")
	t.writeMetric(&b, "Declared", t.Declared)
	t.writeMetric(&b, "Acknowledged", t.Acknowledged)
	t.writeMetric(&b, "Mitigated", t.Mitigated)
	t.writeMetric(&b, "Resolved", t.Resolved)
	if t.MTTA > 0 {
		b.WriteString("- **Time to acknowledge (MTTA):** " + humanDuration(t.MTTA) + "\n")
	}
	if t.TTM > 0 {
		b.WriteString("- **Time to mitigate (TTM):** " + humanDuration(t.TTM) + "\n")
	}
	if t.MTTR > 0 {
		b.WriteString("- **Time to resolve (MTTR):** " + humanDuration(t.MTTR) + "\n")
	}
	b.WriteString("\n")

	b.WriteString("## Timeline\n\n")
	b.WriteString(t.Table())
	return b.String()
}

// Table renders just the chronological event table, in the display timezone.
func (t *Timeline) Table() string {
	var b strings.Builder
	b.WriteString("| Time (" + t.Loc.String() + ") | Source | Event |\n")
	b.WriteString("| --- | --- | --- |\n")
	for _, e := range t.Events {
		b.WriteString("| " + e.Time.In(t.Loc).Format(tsLayout) + " | " + e.Source + " | " + eventCell(e) + " |\n")
	}
	return b.String()
}

func (t *Timeline) writeMetric(b *strings.Builder, label string, ts time.Time) {
	if ts.IsZero() {
		return
	}
	b.WriteString("- **" + label + ":** " + ts.In(t.Loc).Format(tsLayout) + "\n")
}

// eventCell formats a single event for the table's Event column, prefixing a
// marker glyph/label and pipe-escaping the free text.
func eventCell(e Event) string {
	var parts []string
	if e.Pinned {
		parts = append(parts, "📌")
	}
	parts = append(parts, e.Marker.emoji())
	if tt := e.Marker.title(); tt != "" {
		parts = append(parts, tt+" —")
	}
	parts = append(parts, escapeCell(e.Text))
	if e.Actor != "" && e.Actor != "unknown" {
		parts = append(parts, "("+escapeCell(e.Actor)+")")
	}
	return strings.Join(parts, " ")
}

// escapeCell keeps free text from breaking the Markdown table by neutralizing
// pipes and collapsing newlines.
func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.TrimSpace(s)
}

// humanDuration renders a duration as e.g. "1h30m05s", dropping zero leading
// units so short incidents read cleanly.
func humanDuration(d time.Duration) string {
	d = d.Round(time.Second)
	h := d / time.Hour
	d -= h * time.Hour
	m := d / time.Minute
	d -= m * time.Minute
	s := d / time.Second

	var b strings.Builder
	if h > 0 {
		writeUnit(&b, int(h), "h")
	}
	if h > 0 || m > 0 {
		writeUnit(&b, int(m), "m")
	}
	writeUnit(&b, int(s), "s")
	return b.String()
}

func writeUnit(b *strings.Builder, v int, unit string) {
	// Pad to two digits once a larger unit has already been written.
	if b.Len() > 0 && v < 10 {
		b.WriteByte('0')
	}
	b.WriteString(itoa(v))
	b.WriteString(unit)
}

func itoa(v int) string {
	if v == 0 {
		return "0"
	}
	var digits []byte
	for v > 0 {
		digits = append([]byte{byte('0' + v%10)}, digits...)
		v /= 10
	}
	return string(digits)
}
